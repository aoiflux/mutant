package main

import (
	"fmt"
	"sort"
	"strings"

	"mutant/policy/limitscan"
)

// defaultLimitsPath is the third generated artifact: every named limit in the
// tree, with its value and the reason it has that value.
const defaultLimitsPath = "docs/LIMITS_REFERENCE.md"

const limitsTitle = "Mutant limits reference"

// shippedPrograms are the programs a release builds: the mutant binary, the
// language server the editor extension carries, and the WebAssembly REPL. A
// limit in a package any of them is built from bounds a run.
var shippedPrograms = []string{".", "lsp/cmd/mlsp", "cmd/replwasm"}

// toolPrograms are the other programs in the tree. Every program is one or the
// other, so a new one has to be put on a side before the reference renders.
var toolPrograms = []string{"cmd/covreport", "cmd/gendocs", "cmd/sweep", "cmd/wasmreplserve"}

const limitsPreamble = `This document is generated by ` + "`go run ./cmd/gendocs`" + ` from the source tree. Do not edit it by hand;
edit the constant's doc comment and regenerate. ` + "`go run ./cmd/gendocs -check`" + ` fails when it is out of date.

A value that bounds what Mutant will do -- how much it reads, how deep it
recurses, how long it waits, how many entries it keeps -- belongs in a named
constant in the package that enforces it, marked with a ` + "`//mutant:limit <unit>`" + ` directive and
a written reason. These are those constants. A limit that a command-line flag can
change names the flag; nothing here is read from the environment or from a
configuration file (see [CONFIGURATION_POLICY.md](CONFIGURATION_POLICY.md)).

` + "`go test ./policy/`" + ` finds limits by their shape and their name -- a literal
allocation size, a literal timeout, a depth compared with a number, a constant
called ` + "`max...`" + ` with no directive -- and fails on any it finds that is neither
listed here nor held, one entry at a time, in ` + "`policy/limit_budget.go`" + `. A limit
written in a shape the guard does not recognise is in neither place. Values fixed
by a file format or a protocol are not limits; they are marked ` + "`//mutant:format`" + `
and are not listed.

%s
`

// limitsToolsHeading introduces the limits that bound no run.
const limitsToolsHeading = `## The tools around Mutant

These bound the programs that build, test and document Mutant -- the example
sweeper, the generators, the test helpers and the limit guard itself -- and
never a run of it.
`

// renderLimitsReference scans the tree rooted at root and renders every named
// limit. The output carries no line numbers and no absolute paths, so it is the
// same on every host and does not change when unrelated code moves.
func renderLimitsReference(root string) (string, error) {
	result, err := limitscan.Scan(root)
	if err != nil {
		return "", err
	}
	if len(result.Problems) > 0 {
		lines := make([]string, 0, len(result.Problems))
		for _, p := range result.Problems {
			lines = append(lines, "  "+p.String())
		}
		return "", fmt.Errorf("malformed //mutant: directives:\n%s", strings.Join(lines, "\n"))
	}
	if unsided := unsidedPrograms(result); len(unsided) > 0 {
		return "", fmt.Errorf("programs that are neither in shippedPrograms nor in toolPrograms (cmd/gendocs/limits.go): %s",
			strings.Join(unsided, ", "))
	}

	linked := linkedPackages(result)
	var runPackages, toolPackages []string
	byPackage := map[string][]limitscan.Limit{}
	runLimits, toolLimits := 0, 0
	for _, l := range result.Limits {
		if _, seen := byPackage[l.Package]; !seen {
			if linked[l.Package] {
				runPackages = append(runPackages, l.Package)
			} else {
				toolPackages = append(toolPackages, l.Package)
			}
		}
		byPackage[l.Package] = append(byPackage[l.Package], l)
		if linked[l.Package] {
			runLimits++
		} else {
			toolLimits++
		}
	}

	counts := fmt.Sprintf("%s in %s bound a run.", plural(runLimits, "limit"), plural(len(runPackages), "package"))
	if toolLimits > 0 {
		counts += fmt.Sprintf(" %s in %s bound the tools around it.", plural(toolLimits, "limit"), plural(len(toolPackages), "package"))
	}
	if n := len(result.Findings); n > 0 {
		verb := "are"
		if n == 1 {
			verb = "is"
		}
		counts += fmt.Sprintf(" The guard finds %s that %s not named yet; `policy/limit_budget.go` lists each one.", plural(n, "limit"), verb)
	} else {
		counts += " The guard finds no limit that is not named."
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", limitsTitle)
	fmt.Fprintf(&b, limitsPreamble, counts)
	for _, pkg := range runPackages {
		writeLimitsTable(&b, "##", pkg, byPackage[pkg])
	}
	if len(toolPackages) > 0 {
		b.WriteString("\n" + limitsToolsHeading)
		for _, pkg := range toolPackages {
			writeLimitsTable(&b, "###", pkg, byPackage[pkg])
		}
	}
	return b.String(), nil
}

func writeLimitsTable(b *strings.Builder, heading, pkg string, limits []limitscan.Limit) {
	fmt.Fprintf(b, "\n%s `%s`\n\n", heading, pkg)
	b.WriteString("| Limit | Value | Unit | Flag | Why | File |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- |\n")
	for _, l := range limits {
		flag := "--"
		if l.Flag != "" {
			flag = "`" + l.Flag + "`"
		}
		file := "`" + l.File + "`"
		if l.BuildTag != "" {
			file += " (" + escapeTableCell(l.BuildTag) + ")"
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s | %s |\n",
			l.Name, escapeTableCell(l.Value), l.Unit, flag, escapeTableCell(l.Reason), file)
	}
}

// linkedPackages is every package a shipped program is built from, following
// the imports of the files the scan read. Test files are not read, so a package
// only a test imports is not linked.
func linkedPackages(result *limitscan.Result) map[string]bool {
	linked := map[string]bool{}
	var visit func(pkg string)
	visit = func(pkg string) {
		if linked[pkg] {
			return
		}
		linked[pkg] = true
		for dep := range result.Imports[pkg] {
			visit(dep)
		}
	}
	for _, program := range shippedPrograms {
		if result.Mains[program] {
			visit(program)
		}
	}
	return linked
}

// unsidedPrograms lists the programs the scan found that neither list names.
func unsidedPrograms(result *limitscan.Result) []string {
	sided := map[string]bool{}
	for _, p := range shippedPrograms {
		sided[p] = true
	}
	for _, p := range toolPrograms {
		sided[p] = true
	}
	var unsided []string
	for program := range result.Mains {
		if !sided[program] {
			unsided = append(unsided, program)
		}
	}
	sort.Strings(unsided)
	return unsided
}

func plural(n int, noun string) string {
	if n == 1 {
		return fmt.Sprintf("1 %s", noun)
	}
	return fmt.Sprintf("%s %ss", groupThousands(n), noun)
}

// groupThousands writes 1234 as 1,234, the way the tables write their values.
func groupThousands(n int) string {
	s := fmt.Sprint(n)
	var b strings.Builder
	for i, r := range s {
		if i > 0 && (len(s)-i)%3 == 0 {
			b.WriteByte(',')
		}
		b.WriteRune(r)
	}
	return b.String()
}
