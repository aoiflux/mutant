package main

import (
	"fmt"
	"strings"

	"mutant/policy/limitscan"
)

// defaultLimitsPath is the third generated artifact: every named limit in the
// tree, with its value and the reason it has that value.
const defaultLimitsPath = "docs/LIMITS_REFERENCE.md"

const limitsTitle = "Mutant limits reference"

const limitsPreamble = `This document is generated by ` + "`go run ./cmd/gendocs`" + ` from the source tree. Do not edit it by hand;
edit the constant's doc comment and regenerate. ` + "`go run ./cmd/gendocs -check`" + ` fails when it is out of date.

Every value that bounds what Mutant will do -- how much it reads, how deep it
recurses, how long it waits, how many entries it keeps -- is a named constant in
the package that enforces it, marked with a ` + "`//mutant:limit <unit>`" + ` directive and
a written reason. This is the list of them. A limit that a command-line flag can
change names the flag; nothing here is read from the environment or from a
configuration file (see [CONFIGURATION_POLICY.md](CONFIGURATION_POLICY.md)).

A limit that is not listed here is a bare literal somewhere in the source, and
` + "`go test ./policy/`" + ` fails for any that the guard can recognise beyond the budget in
` + "`policy/limit_budget.go`" + `. Values fixed by a file format or a protocol are not
limits; they are marked ` + "`//mutant:format`" + ` and are not listed.

%d limits in %d packages.
`

// renderLimitsReference scans the tree rooted at root and renders every named
// limit. The output carries no line numbers and no absolute paths, so it is the
// same on every host and does not change when unrelated code moves.
func renderLimitsReference(root string) (string, error) {
	result, err := limitscan.Scan(root)
	if err != nil {
		return "", err
	}
	if len(result.Problems) > 0 {
		lines := make([]string, 0, len(result.Problems))
		for _, p := range result.Problems {
			lines = append(lines, "  "+p.String())
		}
		return "", fmt.Errorf("malformed //mutant: directives:\n%s", strings.Join(lines, "\n"))
	}

	packages := make([]string, 0)
	byPackage := map[string][]limitscan.Limit{}
	for _, l := range result.Limits {
		if _, seen := byPackage[l.Package]; !seen {
			packages = append(packages, l.Package)
		}
		byPackage[l.Package] = append(byPackage[l.Package], l)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", limitsTitle)
	fmt.Fprintf(&b, limitsPreamble, len(result.Limits), len(packages))
	for _, pkg := range packages {
		fmt.Fprintf(&b, "\n## `%s`\n\n", pkg)
		b.WriteString("| Limit | Value | Unit | Flag | Why | File |\n")
		b.WriteString("| --- | --- | --- | --- | --- | --- |\n")
		for _, l := range byPackage[pkg] {
			flag := "--"
			if l.Flag != "" {
				flag = "`" + l.Flag + "`"
			}
			file := "`" + l.File + "`"
			if l.BuildTag != "" {
				file += " (" + escapeTableCell(l.BuildTag) + ")"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s |\n",
				l.Name, escapeTableCell(l.Value), l.Unit, flag, escapeTableCell(l.Reason), file)
		}
	}
	return b.String(), nil
}
